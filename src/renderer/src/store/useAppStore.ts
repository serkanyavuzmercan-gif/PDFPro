import { create } from 'zustand'
import type { PDFDocumentProxy } from 'pdfjs-dist'

export type RibbonTabId = 'file' | 'home' | 'edit' | 'view' | 'comment' | 'pages' | 'protect'
export type ToolId =
  | 'select'
  | 'hand'
  | 'addText'
  | 'editText'
  | 'editObject'
  | 'highlight'
  | 'underline'
  | 'strikeout'
  | 'pen'
  | 'eraser'
  | 'stickyNote'
  | 'commentBox'
export type ZoomMode = 'custom' | 'fitPage' | 'fitWidth'
export type ScrollMode = 'continuous' | 'single'
export type SidebarPanel = 'thumbnails' | 'bookmarks'

export interface PageSize {
  /** Displayed size at zoom 1 (rotation applied). */
  width: number
  height: number
  /** Unrotated size of the page's view box. */
  baseWidth: number
  baseHeight: number
  rotation: number
  /** [x0, y0, x1, y1] in PDF user space, as used by pdf.js. */
  viewBox: [number, number, number, number]
}

export interface OpenDocument {
  path: string | null
  name: string
  /** Current file bytes without pending overlay edits; pdf.js receives a copy because it detaches its input. */
  bytes: Uint8Array
  pdf: PDFDocumentProxy
  pageSizes: PageSize[]
}

export type Notice = { kind: 'error' | 'info'; key: string; params?: Record<string, string> }

export const MIN_ZOOM = 0.1
export const MAX_ZOOM = 4
const ZOOM_STEPS = [0.1, 0.25, 0.5, 0.67, 0.75, 0.9, 1, 1.1, 1.25, 1.5, 1.75, 2, 2.5, 3, 4]

export const clampZoom = (z: number): number => Math.min(MAX_ZOOM, Math.max(MIN_ZOOM, z))

export interface AppState {
  activeTab: RibbonTabId
  activeTool: ToolId
  zoom: number
  zoomMode: ZoomMode
  scrollMode: ScrollMode
  sidebarOpen: boolean
  sidebarPanel: SidebarPanel
  document: OpenDocument | null
  loading: boolean
  currentPage: number
  /** 1-based pages selected in the thumbnail panel. */
  selectedPages: number[]
  selectionAnchor: number | null
  /** Incremented on explicit navigation so the viewer scrolls even to the same page. */
  navRequest: { page: number; nonce: number }
  notice: Notice | null

  setActiveTab: (tab: RibbonTabId) => void
  setActiveTool: (tool: ToolId) => void
  setZoom: (zoom: number) => void
  /** Used by the viewer to apply fit-mode zoom without leaving that mode. */
  applyFitZoom: (zoom: number) => void
  zoomIn: () => void
  zoomOut: () => void
  setZoomMode: (mode: ZoomMode) => void
  setScrollMode: (mode: ScrollMode) => void
  toggleSidebar: () => void
  setSidebarPanel: (panel: SidebarPanel) => void
  setLoading: (loading: boolean) => void
  setDocument: (doc: OpenDocument | null) => void
  /** Swaps in re-generated bytes (page operations, undo) while keeping the view position. */
  replaceDocumentContent: (content: Pick<OpenDocument, 'bytes' | 'pdf' | 'pageSizes'>, page?: number) => void
  updateDocument: (patch: Partial<Pick<OpenDocument, 'path' | 'name'>>) => void
  setCurrentPage: (page: number) => void
  goToPage: (page: number) => void
  selectPage: (page: number, mode: 'single' | 'toggle' | 'range') => void
  showNotice: (notice: Notice | null) => void
}

export const useAppStore = create<AppState>((set, get) => ({
  activeTab: 'home',
  activeTool: 'select',
  zoom: 1,
  zoomMode: 'fitWidth',
  scrollMode: 'continuous',
  sidebarOpen: true,
  sidebarPanel: 'thumbnails',
  document: null,
  loading: false,
  currentPage: 1,
  selectedPages: [],
  selectionAnchor: null,
  navRequest: { page: 1, nonce: 0 },
  notice: null,

  setActiveTab: (activeTab) => set({ activeTab }),
  setActiveTool: (activeTool) => set({ activeTool }),
  setZoom: (zoom) => set({ zoom: clampZoom(zoom), zoomMode: 'custom' }),
  applyFitZoom: (zoom) => set({ zoom: clampZoom(zoom) }),
  zoomIn: () => {
    const { zoom } = get()
    const next = ZOOM_STEPS.find((s) => s > zoom + 0.001) ?? MAX_ZOOM
    set({ zoom: next, zoomMode: 'custom' })
  },
  zoomOut: () => {
    const { zoom } = get()
    const next = [...ZOOM_STEPS].reverse().find((s) => s < zoom - 0.001) ?? MIN_ZOOM
    set({ zoom: next, zoomMode: 'custom' })
  },
  setZoomMode: (zoomMode) => set(zoomMode === 'custom' ? { zoomMode, zoom: 1 } : { zoomMode }),
  setScrollMode: (scrollMode) => set({ scrollMode }),
  toggleSidebar: () => set((s) => ({ sidebarOpen: !s.sidebarOpen })),
  setSidebarPanel: (sidebarPanel) => set({ sidebarPanel, sidebarOpen: true }),
  setLoading: (loading) => set({ loading }),
  setDocument: (document) => {
    const previous = get().document
    if (previous && previous.pdf !== document?.pdf) void previous.pdf.loadingTask.destroy()
    set({
      document,
      currentPage: 1,
      selectedPages: [],
      selectionAnchor: null,
      navRequest: { page: 1, nonce: get().navRequest.nonce + 1 }
    })
  },
  replaceDocumentContent: (content, page) => {
    const previous = get().document
    if (!previous) return
    if (previous.pdf !== content.pdf) void previous.pdf.loadingTask.destroy()
    const count = content.pageSizes.length
    const target = Math.min(count, Math.max(1, page ?? get().currentPage))
    set({
      document: { ...previous, ...content },
      currentPage: target,
      selectedPages: get().selectedPages.filter((p) => p <= count),
      navRequest: page ? { page: target, nonce: get().navRequest.nonce + 1 } : get().navRequest
    })
  },
  updateDocument: (patch) => {
    const doc = get().document
    if (doc) set({ document: { ...doc, ...patch } })
  },
  setCurrentPage: (currentPage) => set({ currentPage }),
  goToPage: (page) => {
    const count = get().document?.pageSizes.length ?? 0
    if (count === 0) return
    const target = Math.min(count, Math.max(1, Math.round(page)))
    set({ currentPage: target, navRequest: { page: target, nonce: get().navRequest.nonce + 1 } })
  },
  selectPage: (page, mode) => {
    const { selectedPages, selectionAnchor } = get()
    if (mode === 'toggle') {
      const next = selectedPages.includes(page)
        ? selectedPages.filter((p) => p !== page)
        : [...selectedPages, page].sort((a, b) => a - b)
      set({ selectedPages: next, selectionAnchor: page })
      return
    }
    if (mode === 'range' && selectionAnchor !== null) {
      const [from, to] = selectionAnchor < page ? [selectionAnchor, page] : [page, selectionAnchor]
      set({ selectedPages: Array.from({ length: to - from + 1 }, (_, i) => from + i) })
      return
    }
    set({ selectedPages: [page], selectionAnchor: page })
  },
  showNotice: (notice) => set({ notice })
}))

/** Pages an operation applies to: the thumbnail selection, otherwise the current page (1-based). */
export function targetPages(state: AppState = useAppStore.getState()): number[] {
  return state.selectedPages.length > 0 ? state.selectedPages : [state.currentPage]
}
